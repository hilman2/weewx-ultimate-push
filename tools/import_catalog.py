"""Build the field catalog from Werner Krenn's ecowittcustom driver.

The catalog is data, not code, and it should stay traceable to where it came from.
Rather than retyping five hundred field names, this reads them out of the source with
the ast module and writes catalogs/ecowitt.py.

Usage:

    python tools/import_catalog.py path/to/ecowittcustom.py

The result is reviewed and committed like any other file. Run it again when upstream
adds fields, and the diff shows exactly what changed.
"""

